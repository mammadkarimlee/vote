  on gr.org_id = 'default'
 and gr.branch_id = br.id
 and gr.name = s.group_name
on conflict (id) do update
set name = excluded.name,
    branch_id = excluded.branch_id,
    group_id = excluded.group_id,
    class_level = excluded.class_level,
    deleted_at = null,
